/**
 * What `!` commands tell Claude: the CLI's own bash-mode format (a caveat, then the command and its output as tags), put
 * in front of the next message that goes to the CLI. A `!` command costs no model call by itself.
 */
const store = require('../session-store');
const { publish } = require('../session-common');

const MAX_ENTRIES = 10; // older ones are dropped
const MAX_CHARS = 30000; // of output for the model, over all the entries
const CAVEAT = 'Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.';

const pending = sessionId => store.get(sessionId)?.shellContext || [];

function add(sessionId, entry) {
  publish(store.update(sessionId, { shellContext: [...pending(sessionId), entry].slice(-MAX_ENTRIES) }));
}

/** Puts back what withPending took, when the message it was in front of did not reach the CLI. */
function restore(sessionId, entries) {
  if (entries.length) publish(store.update(sessionId, { shellContext: [...entries, ...pending(sessionId)].slice(-MAX_ENTRIES) }));
}

function clear(sessionId) {
  if (pending(sessionId).length) publish(store.update(sessionId, { shellContext: [] }));
}

function entryText({ command, stdout, stderr, exitCode }, budget) {
  const out = stdout.slice(0, budget);
  const err = `${stderr}${exitCode ? `${stderr && !stderr.endsWith('\n') ? '\n' : ''}exit code: ${exitCode}` : ''}`.slice(0, Math.max(0, budget - out.length));
  return `<bash-input>${command}</bash-input>\n<bash-stdout>${out}</bash-stdout><bash-stderr>${err}</bash-stderr>`;
}

/**
 * The message text with the pending commands in front, which are then forgotten. A slash command stays untouched (the CLI
 * reads it only at the start of the text), and the commands wait for the next message.
 * @returns {string}
 */
function withPending(sessionId, text) {
  const entries = pending(sessionId);
  if (!entries.length || text.trimStart().startsWith('/')) return text;
  const budget = Math.floor(MAX_CHARS / entries.length);
  clear(sessionId);
  return [CAVEAT, ...entries.map(entry => entryText(entry, budget)), text].join('\n');
}

module.exports = { add, clear, restore, pending, withPending };
